'use client';
import { useQuery } from '@tanstack/react-query';
import Link from 'next/link';
import type { ReactNode } from 'react';
import { Button } from '@/components/ui/primitives';
import { api, downloadFile, fileUrl } from '@/lib/api';
import { SelectBox } from '@/components/ui/select-box';

export type Orientation = 'portrait' | 'landscape';
export const money = (v: unknown) => Number(v ?? 0).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
export const num = (v: unknown) => Number(v ?? 0).toLocaleString('en-IN', { maximumFractionDigits: 4 });

export interface Company { name: string; address?: string | null; phone?: string | null; email?: string | null; gstin?: string | null; currencyCode?: string; footerNote?: string | null; logoUrl?: string | null }

export function useCompany() {
  return useQuery({ queryKey: ['company'], queryFn: () => api<Company>('/company-settings'), staleTime: 5 * 60_000 });
}

/** Letterhead: logo, company name, address, contact and GSTIN. */
export function CompanyHeader({ company }: { company?: Company }) {
  if (!company) return null;
  return (
    <header className="flex items-start gap-3 border-b-2 border-slate-800 pb-2">
      {company.logoUrl && /* eslint-disable-next-line @next/next/no-img-element */ <img src={fileUrl(company.logoUrl)} alt="" className="h-14 w-auto max-w-[110px] object-contain" />}
      <div className="text-xs text-slate-600">
        <p className="text-base font-semibold text-slate-900">{company.name}</p>
        {company.address && <p>{company.address}</p>}
        <p>{[company.phone && `Tel ${company.phone}`, company.email].filter(Boolean).join(' | ')}</p>
        {company.gstin && <p>GSTIN {company.gstin}</p>}
        {company.currencyCode && <p>Amounts in {company.currencyCode}{(company as { currencySymbol?: string }).currencySymbol ? ` (${(company as { currencySymbol?: string }).currencySymbol})` : ''}</p>}
      </div>
    </header>
  );
}

/**
 * Print preview chrome: paper orientation, Print and "Download PDF" (server-generated), hidden when printing.
 * The page size is set with an @page rule so the browser's own print dialog starts with the chosen orientation.
 */
export function PrintShell({ orientation, onOrientation, pdfPath, pdfName, backHref, extra, children }: {
  orientation: Orientation; onOrientation: (o: Orientation) => void; pdfPath: string; pdfName: string; backHref: string; extra?: ReactNode; children: ReactNode;
}) {
  return (
    <div className="space-y-4">
      <style>{`@media print { @page { size: A4 ${orientation}; margin: 10mm; } body { background: #fff; } }`}</style>
      <div className="flex flex-wrap items-center gap-2 print:hidden">
        <label className="text-sm">Paper
          <SelectBox className="ml-2 h-9 rounded-md border border-slate-300 bg-white px-2 text-sm" value={orientation} onChange={(e) => onOrientation(e.target.value as Orientation)}>
            <option value="portrait">A4 portrait</option><option value="landscape">A4 landscape</option>
          </SelectBox>
        </label>
        {extra}
        <Button onClick={() => window.print()}>Print</Button>
        <Button variant="outline" onClick={() => void downloadFile(`${pdfPath}${pdfPath.includes('?') ? '&' : '?'}orientation=${orientation}`, pdfName)}>Download PDF</Button>
        <Link href={backHref}><Button variant="outline">Back</Button></Link>
      </div>
      <p className="text-xs text-slate-500 print:hidden">Preview of the printed page. Use Print for the browser print dialog or Download PDF for a file generated by the server.</p>
      <div className={`mx-auto rounded border border-slate-200 bg-white p-4 shadow-sm print:border-0 print:p-0 print:shadow-none ${orientation === 'landscape' ? 'max-w-[1050px]' : 'max-w-[760px]'}`}>{children}</div>
    </div>
  );
}
